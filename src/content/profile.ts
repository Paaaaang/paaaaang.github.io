/**
 * 자료 슬롯.
 *
 * `src` 가 비어 있으면 화면에 "여기에 무엇이 들어갈 자리인지"를 적은
 * 빈 프레임이 그려진다. 나중에 파일을 `public/media/<케이스 id>/` 에 넣고
 * 아래 `src` 만 채우면 그 자리에 바로 들어간다. 레이아웃은 변하지 않는다.
 */
export type MediaSlot = {
  /** 예: '/media/interview-ops/architecture.png' — 비우면 빈 프레임 */
  src?: string
  /** 화면에 보이는 캡션이자, 비어 있을 때의 안내 문구 */
  caption: string
  /** 자료 종류. 빈 프레임에 라벨로 표시된다. */
  kind: '아키텍처' | '화면 설계' | '기획 문서' | '발표 자료' | '현장 사진' | '지표'
  /** 프레임 비율. 가로로 긴 다이어그램은 wide, 앱 화면은 portrait.
   *  natural 은 원본 비율을 그대로 쓴다. 문서 캡처처럼 잘리면 안 되는 자료용. */
  ratio?: 'wide' | 'video' | 'square' | 'portrait' | 'natural'
  /** 스크린리더용 대체 텍스트. 실제 이미지를 넣을 때 반드시 채운다. */
  alt?: string
  /** 흰 바탕 문서. 잉크 배경 위에서 종이 한 장처럼 보이게 여백을 준다. */
  light?: boolean
  /**
   * 원본 픽셀 크기. natural 비율 이미지는 이 값으로 자리를 먼저 잡는다.
   * 없으면 이미지가 늦게 뜰 때 페이지 길이가 바뀌어 핀 구간 위치가 어긋난다.
   */
  size?: [number, number]
  /** 휴대폰 화면처럼 좁은 캡처. 칸 가운데에 실제 폭 가까이 놓는다. */
  narrow?: boolean
  /** 갤러리에서 차지하는 폭. 정하지 않으면 첫 자료만 full.
   *  half 는 나온 순서대로 둘씩 짝을 짓고, 짝이 없는 마지막 half 는 full 로 선다. */
  span?: 'full' | 'half'
  /**
   * 한 줄 자료의 16:7 높이 제한을 풀고 원본 비율 그대로 보인다.
   * 경험의 핵심 그림(아키텍처)처럼 줄이면 안 읽히는 자료에만 쓴다.
   */
  uncapped?: boolean
  /** 틀 바탕색. 어두운 그림은 그림 배경과 같은 색을 깔아 틀 경계가 보이지 않게 한다. */
  backdrop?: string
}

